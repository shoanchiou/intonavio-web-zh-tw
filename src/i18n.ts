export let locale: "zh-TW" | "en" =
  localStorage.getItem("intonavio-locale") === "en" ? "en" : "zh-TW";
export function t(key: Key): string {
  return (locale === "en" ? en : zhTW)[key];
}
export function setLocale(value: "zh-TW" | "en"): void {
  locale = value;
  localStorage.setItem("intonavio-locale", value);
  document.documentElement.lang = value;
  document.title = `Intonavio｜${t("app")}`;
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n as Key);
  });
}
